import { Config } from "effect"
import { appEnv, appEnvTruthy } from "../identity"

export function truthy(key: string) {
  const value = process.env[key]?.toLowerCase()
  return value === "true" || value === "1"
}

function enabledByExperimental(key: string) {
  const explicit = appEnv(key)
  if (explicit !== undefined) return appEnvTruthy(key)
  return appEnvTruthy("NOVACODE_EXPERIMENTAL")
}

function configBool(key: string) {
  return Config.boolean(key).pipe(Config.withDefault(false))
}

